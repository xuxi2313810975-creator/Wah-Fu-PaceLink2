import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
await fs.mkdir('test-results',{recursive:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[],calls=[],responses=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.url().includes('/api/route'))calls.push(r.url());});
page.on('response',async r=>{if(r.url().includes('/api/route'))try{responses.push(await r.json());}catch{}});
const action=a=>page.locator(`[data-action="${a}"]`);
const title=()=>page.locator('[data-flow-title]').innerText();
const english=async()=>assert.equal(/[\u3400-\u9fff]/u.test((await page.locator('body').innerText()).replace('繁體中文','')),false,'Untranslated visible Chinese');
const waitJourney=async()=>{await action('reached').waitFor({timeout:55000});assert.ok(await page.locator('.stage-line').getAttribute('d'));};
const finish=async()=>{let steps=0;while(await action('reached').count()){assert.ok(++steps<=12);await action('reached').click();}return steps;};
await page.goto('http://127.0.0.1:4173/?lang=en&origin=H17&destination=B3&direction=out&rest=6');
await action('rest').click();assert.equal(await page.locator('#position-error').isVisible(),true);
await page.locator('#demo-position').selectOption('0.3333333333333333');
await action('rest').click();assert.equal(await page.locator('.rest-card').count(),3);await english();
await page.locator('[data-action="pick-rest"][data-id="R3"]').click();await waitJourney();
assert.match(await page.locator('.flow-body').innerText(),/Wah Lam Path/);
await page.locator('[data-lang="zh"]').click();assert.match(await title(),/這一段 1/);
await page.locator('[data-lang="en"]').click();await english();
await page.screenshot({path:'test-results/wahfu-v2-stage-en.png',fullPage:true});
await finish();assert.equal(await title(),'Take a moment to rest.');assert.match(await page.locator('.rest-allowance').innerText(),/6 min/);
await page.screenshot({path:'test-results/wahfu-v2-rest-en.png',fullPage:true});
await action('continue').click();await waitJourney();assert.match(await page.locator('.flow-body').innerText(),/Wah Fu \(North\)/);
await action('reached').click();
const beforeHome=calls.length;await action('home').click();await waitJourney();
assert.ok(calls.length>beforeHome,'Return home must query from the last confirmed intermediate position');
assert.match(await page.locator('.flow-body').innerText(),/Wah Sang House/);
await english();await finish();assert.match(await title(),/Back at the home network/);
await action('home').click();assert.equal(await action('reached').count(),0,'Already at home should not invent a new walk');
await action('restart').click();
// Saved, independently queried directional routes work without a network request.
await page.locator('#origin').selectOption('H13');await page.locator('#destination').selectOption('R3');
await page.locator('#demo-position').selectOption('0');const n=calls.length;
await action('continue').click();await waitJourney();assert.equal(calls.length,n);
await page.locator('[data-lang="zh"]').click();await action('text-size').click();
for(const width of [390,320]){
 await page.setViewportSize({width,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width} large text`);
 await page.screenshot({path:`test-results/wahfu-v2-stage-zh-${width}.png`,fullPage:true});
}
await page.locator('[data-lang="en"]').click();await english();
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'English large text overflow');
await page.locator('#origin').selectOption('H14');await page.locator('#destination').selectOption('B3');
assert.equal(await action('rest').isDisabled(),true);
await page.locator('#origin').selectOption('H13');await page.locator('#destination').selectOption('R3');
await page.locator('#demo-position').selectOption('0.3333333333333333');
// Service errors, withheld estimates, cancellation and route changes are deterministic failure tests.
await page.route('**/api/route?*',r=>r.fulfill({status:503,contentType:'application/json',body:'{"status":"unavailable"}'}));
await action('home').click();await action('retry').waitFor();assert.match(await title(),/not available/);assert.equal(await action('reached').count(),0);await english();
await page.unroute('**/api/route?*');
await page.route('**/api/route?*',r=>r.fulfill({status:200,contentType:'application/json',body:'{"status":"withheld","valid":false}'}));
await action('retry').click();await action('retry').waitFor();assert.match(await page.locator('.flow-error').innerText(),/nearly coincide/);await english();
await page.unroute('**/api/route?*');
let release;const gate=new Promise(r=>release=r);await page.route('**/api/route?*',async r=>{await gate;await r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(responses.find(x=>x.valid))}).catch(()=>{});});
await action('retry').click();await action('cancel').waitFor();await action('cancel').click();release();await page.waitForTimeout(120);assert.match(await title(),/What would/);assert.equal(await action('reached').count(),0);
await page.unroute('**/api/route?*');
await page.setViewportSize({width:1440,height:1100});await action('text-size').click();await page.locator('[data-lang="zh"]').click();
await page.screenshot({path:'test-results/wahfu-v2-home-zh.png',fullPage:true});
assert.deepEqual(errors,[]);
await fs.writeFile('test-results/wahfu-v2-test-result.json',JSON.stringify({passed:true,errors,checks:['real API: intermediate position to rest space','rest complete → original destination','return home from last completed section','language preserves stage','saved directional route reuse','already-home handling','unverified original route disabled','large text at 320/390px','English UI translation','service failure and withheld estimate','cancel rejects stale response'],realRoutes:responses.filter(x=>x.valid).map(x=>({metres:x.metres,barrierFree:x.barrierFree,startSnap:x.startSnap,endSnap:x.endSnap,retrievedAt:x.retrievedAt}))},null,2));
console.log('Journey flow checks passed. Real route queries:',responses.filter(x=>x.valid).length);await browser.close();
